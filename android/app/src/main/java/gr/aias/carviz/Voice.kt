package gr.aias.carviz

/**
 * Η γέφυρα ανάμεσα στην υπηρεσία φωνής και τη ζωγραφική.
 *
 * Δύο μεγέθη, τα ίδια που δέχεται το `window.AIAS` στο πρωτότυπο. Ο renderer
 * δεν ξέρει τίποτα για μικρόφωνα, WebSocket ή ElevenLabs — διαβάζει `level`
 * και `mode` και ζωγραφίζει. Αν αύριο αλλάξει ο πάροχος, αλλάζει μόνο ό,τι
 * γράφει εδώ.
 *
 * **Η στάθμη βγαίνει από τον ήχο που ΑΝΑΠΑΡΑΓΟΥΜΕ, όχι από το μικρόφωνο.**
 * Το μικρόφωνο χρειάζεται για να μας ακούει ο agent· η ζωγραφική όμως παίρνει
 * την ένταση από το ίδιο buffer που στέλνουμε στα ηχεία. Έτσι ο συγχρονισμός
 * είναι ακριβής, χωρίς ηχώ από την καμπίνα και χωρίς δεύτερο διεκδικητή του
 * μικροφώνου. Και στην ακρόαση η στάθμη δεν χρειάζεται καν: το κύμα τρέχει με
 * δική του φάση.
 */
object Voice {

    /** Τρέχει η υπηρεσία; Αν όχι, ο renderer γυρίζει στον συνθετικό οδηγό. */
    @Volatile var active = false

    /** 0..1 — η ένταση της φωνής του ΑΙΑΝΤΑ όσο μιλάει. */
    @Volatile var level = 0f

    /** 'idle' | 'listen' | 'speak' */
    @Volatile var mode = "idle"

    /** Ανθρώπινη περιγραφή, για την οθόνη διαγνωστικών στο κινητό. */
    @Volatile var status = "ανενεργή"

    /** Τα τελευταία που ειπώθηκαν, για να φαίνεται ότι όντως συνεννοούνται. */
    @Volatile var lastUser = ""
    @Volatile var lastAgent = ""

    fun reset() {
        active = false
        level = 0f
        mode = "idle"
        lastUser = ""
        lastAgent = ""
    }
}
