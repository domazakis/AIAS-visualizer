package gr.aias.carviz

/**
 * Η γέφυρα ανάμεσα στην υπηρεσία φωνής και τη ζωγραφική.
 *
 * Δύο μεγέθη, τα ίδια που δέχεται το `window.AIAS` στο πρωτότυπο. Ο renderer
 * δεν ξέρει τίποτα για μικρόφωνα, WebSocket ή ElevenLabs — διαβάζει `level`
 * και `mode` και ζωγραφίζει. Αν αύριο αλλάξει ο πάροχος, αλλάζει μόνο ό,τι
 * γράφει εδώ.
 *
 * **Η στάθμη βγαίνει από τον ήχο που ΒΓΑΙΝΕΙ ΑΥΤΗ ΤΗ ΣΤΙΓΜΗ από το ηχείο**,
 * όχι από το μικρόφωνο και όχι από τη στιγμή που παραλάβαμε το πακέτο. Την
 * ορίζει η θέση της κεφαλής αναπαραγωγής πάνω σε μια περιβάλλουσα των 20 ms
 * (δες [VoiceService]). Έτσι ο συγχρονισμός είναι ταυτότητα και όχι εκτίμηση:
 * η τελεία ανεβαίνει με τη συλλαβή που ακούγεται, όχι με εκείνη που θα
 * ακουστεί σε μισό δευτερόλεπτο.
 */
object Voice {

    /** Τρέχει η υπηρεσία; Αν όχι, ο renderer γυρίζει στον συνθετικό οδηγό. */
    @Volatile var active = false

    /** 0..1 — η ένταση της φωνής του ΑΙΑΝΤΑ όσο μιλάει. */
    @Volatile var level = 0f

    /** 'idle' | 'listen' | 'speak' */
    @Volatile var mode = "idle"

    /** Ανθρώπινη περιγραφή, για την οθόνη διαγνωστικών στο κινητό. */
    @Volatile var status = "ανενεργή"

    /** Τα τελευταία που ειπώθηκαν, για να φαίνεται ότι όντως συνεννοούνται. */
    @Volatile var lastUser = ""
    @Volatile var lastAgent = ""

    /**
     * Πού βγήκε τελικά ο ήχος — «ηχείο κινητού», «Bluetooth», «USB».
     *
     * Στο αυτοκίνητο δεν ακούστηκε τίποτα, και χωρίς αυτό δεν ξεχώριζε το «δεν
     * ήρθε ήχος» από το «ήρθε αλλά βγήκε αλλού».
     */
    @Volatile var route = "—"

    /**
     * Η δυνατότερη στιγμή του μικροφώνου μέσα στο παράθυρο διάγνωσης.
     *
     * Κορυφή και όχι στιγμιαία τιμή: η πηγή VOICE_COMMUNICATION περνάει από
     * καταστολή θορύβου, οπότε στη σιωπή δίνει καθαρό μηδέν και μια στιγμιαία
     * μέτρηση δεν λέει τίποτα. Αν η κορυφή μένει μηδέν ενώ μιλάς, το μικρόφωνο
     * το κρατάει άλλος — ο Βοηθός του αυτοκινήτου είναι ο υποψήφιος.
     */
    @Volatile var micHi = 0f

    fun noteMic(v: Float) { if (v > micHi) micHi = v }

    /**
     * Εύρος στάθμης των τελευταίων δειγμάτων, μόνο για διάγνωση.
     *
     * Μπήκε επειδή δύο φορές ρυθμίσαμε την ένταση στα τυφλά και δύο φορές
     * βγήκε λάθος. Αν το ελάχιστο και το μέγιστο είναι κολλημένα μαζί, δεν
     * υπάρχει δυναμική και το ξέρουμε με νούμερο αντί για εντύπωση.
     */
    @Volatile var lo = 1f
    @Volatile var hi = 0f

    /**
     * Ιστόγραμμα του ωμού λόγου `ένταση/κορυφή`, σε πέντε κάδους του 0,2.
     *
     * Το εύρος [lo]–[hi] είπε ότι υπάρχει δυναμική, αλλά όχι **πού κάθεται**:
     * βγήκε 0,00–1,00 και η εικόνα ήταν κολλημένη στο τέρμα, που σημαίνει ότι
     * η κατανομή ήταν στριμωγμένη ψηλά και τα άκρα ήταν στιγμιαία. Με το
     * ιστόγραμμα η καμπύλη απόκρισης υπολογίζεται αντί να ρυθμίζεται με το
     * μάτι — τρίτη φορά που θα ρυθμιζόταν στα τυφλά.
     */
    val hist = IntArray(5)

    fun note(v: Float) {
        if (v < lo) lo = v
        if (v > hi) hi = v
    }

    /**
     * Το ίδιο, αλλά για την **έκταση** που βγαίνει μετά την εξομάλυνση.
     *
     * Δύο ιστογράμματα γιατί οι δύο ερωτήσεις είναι διαφορετικές: το πρώτο λέει
     * αν η στάθμη έχει δυναμική, το δεύτερο αν η δυναμική φτάνει ως το ύψος
     * της μπάρας. Η πρώτη μέτρηση απάντησε «ναι» και η εικόνα ήταν πάλι
     * κολλημένη — άρα η απώλεια ήταν ανάμεσά τους.
     */
    val extHist = IntArray(5)

    fun noteRaw(norm: Float) {
        val b = (norm * 5f).toInt().coerceIn(0, 4)
        synchronized(hist) { hist[b]++ }
    }

    fun noteExt(v: Float) {
        val b = (v * 5f).toInt().coerceIn(0, 4)
        synchronized(extHist) { extHist[b]++ }
    }

    fun histLine(): String = pct(hist)
    fun extLine(): String = pct(extHist)

    private fun pct(a: IntArray): String = synchronized(a) {
        val n = a.sum().coerceAtLeast(1)
        a.joinToString("/") { "%d".format(it * 100 / n) }
    }

    /** Καλείται μία φορά το δευτερόλεπτο, αφού καταγραφεί το εύρος. */
    fun rollWindow() {
        lo = 1f; hi = 0f; micHi = 0f
        synchronized(hist) { java.util.Arrays.fill(hist, 0) }
        synchronized(extHist) { java.util.Arrays.fill(extHist, 0) }
    }

    fun reset() {
        active = false
        level = 0f
        mode = "idle"
        lastUser = ""
        lastAgent = ""
        route = "—"
        micHi = 0f
        lo = 1f
        hi = 0f
    }
}
