package gr.aias.carviz

import android.content.Context

/**
 * Από πού ακούγεται ο ΑΙΑΣ: από τα ηχεία του αυτοκινήτου ή από το κινητό.
 *
 * ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΕΠΙΛΟΓΗ, ΕΝΩ Η 32 ΕΙΧΕ ΑΠΟΦΑΣΙΣΕΙ ΟΡΙΣΤΙΚΑ.
 *
 * Η απόφαση «ο ήχος μένει στο κινητό» βασίστηκε σε σωστή διάγνωση —η ακύρωση
 * ηχούς θέλει σήμα αναφοράς, και ο ακυρωτής του κινητού ξέρει μόνο ό,τι παίζει
 * το κινητό— αλλά σε **ελλιπή απαρίθμηση των δρόμων**. Υπάρχει και τρίτος:
 *
 * - **A2DP**, το κανάλι μουσικής. Το αυτοκίνητο παίζει, το μικρόφωνό του δεν
 *   συμμετέχει, κανείς δεν ακυρώνει. Εδώ πέσαμε στις 32 και 34, και εδώ
 *   γεννιόταν η ηχώ.
 * - **Ηχείο κινητού.** Ακυρώνει ο ακυρωτής του κινητού. Δουλεύει, αλλά η φωνή
 *   ακούγεται από τη μεριά σου και όχι από την καμπίνα.
 * - **HFP/SCO**, το κανάλι κλήσης. Το αυτοκίνητο παίζει από τα ηχεία του
 *   **και δίνει το δικό του μικρόφωνο**, οπότε ακυρώνει με τον δικό του
 *   ακυρωτή — αυτόν που έχει κάθε hands-free για τις κλήσεις.
 *
 * Ο τρίτος δρόμος δεν είχε δοκιμαστεί ποτέ. Ο χρήστης τον βρήκε εμπειρικά:
 * το ChatGPT Voice στο ίδιο αυτοκίνητο ακούγεται δυνατά από τα ηχεία, με το
 * μικρόφωνο του αυτοκινήτου, **χωρίς καμία ηχώ σε καμία ένταση**. Παίζει με
 * την ίδια χρήση με εμάς (`USAGE_VOICE_COMMUNICATION`, μετρημένο στο
 * `dumpsys audio`) — άρα η διαφορά δεν ήταν ποτέ η χρήση, ήταν η **συσκευή**.
 *
 * Προεπιλογή το αυτοκίνητο: είναι το ζητούμενο, και αν δεν υπάρχει γραμμή
 * κλήσης η δρομολόγηση πέφτει μόνη της στο ηχείο του κινητού.
 */
object Route {

    private const val FILE = "aias-route"
    private const val KEY = "car"

    fun inCar(ctx: Context): Boolean =
        ctx.getSharedPreferences(FILE, Context.MODE_PRIVATE).getBoolean(KEY, true)

    fun set(ctx: Context, car: Boolean) {
        ctx.getSharedPreferences(FILE, Context.MODE_PRIVATE)
            .edit().putBoolean(KEY, car).apply()
    }

    fun label(ctx: Context): String =
        if (inCar(ctx)) "Ήχος: από το αυτοκίνητο" else "Ήχος: από το κινητό"
}
